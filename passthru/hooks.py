"""libvirt hook scripts for one VM (single-GPU handoff + performance tuning).

Files land in /etc/libvirt/hooks/qemu.d/<vm>/{prepare/begin,release/end}/ and are
run by the /etc/libvirt/hooks/qemu dispatcher in name order. That dispatcher only
returns the status of the *last* script, so the perf script leaves an abort mark
that the (last) display script turns into a failure before touching the screen.

Every script honours PASSTHRU_DRYRUN=1: commands that change the system are
printed instead of run, state goes to a temp dir. Used by the self-test.
"""

import os

from . import host, model

HOOK_ROOT = "/etc/libvirt/hooks/qemu.d"
DISPATCHER = "/etc/libvirt/hooks/qemu"

COMMON = r'''#!/bin/bash
# passthru: VM "{name}", {phase}. Generated by ~/passthru — rebuilt on every save.
VM={name}
if [ -n "$PASSTHRU_DRYRUN" ]; then
    STATE=${{PASSTHRU_STATE:-$(mktemp -d)}}
else
    STATE=/run/passthru-$VM
fi
mkdir -p "$STATE"
run() {{ if [ -n "$PASSTHRU_DRYRUN" ]; then echo "+ $*"; else "$@"; fi; }}
put() {{ if [ -n "$PASSTHRU_DRYRUN" ]; then echo "+ echo $1 > $2"; else echo "$1" > "$2"; fi; }}
log() {{ echo "$*"; [ -n "$PASSTHRU_DRYRUN" ] || logger -t passthru "$VM: $*"; }}
'''

PERF_BEGIN = r'''
HOST_CPUS="{host_cpus}"
HUGEPAGES={hugepages}
GOVERNOR={governor}
ISOLATE={isolate}
rm -f "$STATE/abort"

if [ "$GOVERNOR" = 1 ]; then
    cat /sys/devices/system/cpu/cpu0/cpufreq/scaling_governor > "$STATE/governor" 2>/dev/null
    for g in /sys/devices/system/cpu/cpu*/cpufreq/scaling_governor; do
        [ -f "$g" ] && put performance "$g"
    done
fi

if [ "$HUGEPAGES" -gt 0 ]; then
    NR=/sys/kernel/mm/hugepages/hugepages-2048kB/nr_hugepages
    HAVE=$(cat "$NR")
    echo "$HAVE" > "$STATE/hugepages"
    WANT=$((HAVE + HUGEPAGES))
    run sync
    put 3 /proc/sys/vm/drop_caches
    put 1 /proc/sys/vm/compact_memory
    put "$WANT" "$NR"
    if [ -z "$PASSTHRU_DRYRUN" ]; then
        GOT=$(cat "$NR")
        if [ "$GOT" -lt "$WANT" ]; then
            log "hugepages: нужно $WANT, выделилось $GOT — память фрагментирована, VM не запускаю"
            put "$HAVE" "$NR"
            touch "$STATE/abort"
            exit 1
        fi
    fi
    log "hugepages: $WANT x 2 MiB"
fi

if [ "$ISOLATE" = 1 ]; then
    for unit in init.scope system.slice user.slice; do
        run systemctl set-property --runtime -- "$unit" AllowedCPUs="$HOST_CPUS"
    done
fi
exit 0
'''

PERF_END = r'''
ALL_CPUS=$(cat /sys/devices/system/cpu/online)
for unit in init.scope system.slice user.slice; do
    run systemctl set-property --runtime -- "$unit" AllowedCPUs="$ALL_CPUS"
done

GOV=$(cat "$STATE/governor" 2>/dev/null)
if [ -n "$GOV" ]; then
    for g in /sys/devices/system/cpu/cpu*/cpufreq/scaling_governor; do
        [ -f "$g" ] && put "$GOV" "$g"
    done
fi

HP=$(cat "$STATE/hugepages" 2>/dev/null)
[ -n "$HP" ] && put "$HP" /sys/kernel/mm/hugepages/hugepages-2048kB/nr_hugepages
rm -f "$STATE/governor" "$STATE/hugepages" "$STATE/abort"
exit 0
'''

DISPLAY_BEGIN = r'''
FALLBACK_DM="{dm}"
UNBIND_CONSOLE={unbind}

if [ -e "$STATE/abort" ]; then
    log "подготовка не удалась — экран не трогаю, запуск отменён"
    exit 1
fi

DM=$(basename "$(readlink -f /etc/systemd/system/display-manager.service)" .service 2>/dev/null)
[ -n "$DM" ] && [ "$DM" != display-manager ] || DM="$FALLBACK_DM"
rm -f "$STATE/dm" "$STATE/consoles" "$STATE/nvidia"
if [ -n "$DM" ] && systemctl is-active --quiet "$DM.service"; then
    echo "$DM" > "$STATE/dm"
    log "останавливаю $DM — GPU уходит в VM"
    run systemctl stop "$DM.service"
    for _ in $(seq 30); do
        systemctl is-active --quiet "$DM.service" || break
        [ -n "$PASSTHRU_DRYRUN" ] && break
        sleep 0.5
    done
fi

if [ "$UNBIND_CONSOLE" = 1 ]; then
    for vt in /sys/class/vtconsole/vtcon*; do
        if grep -q "frame buffer" "$vt/name" 2>/dev/null; then
            put 0 "$vt/bind"
            basename "$vt" >> "$STATE/consoles"
        fi
    done
    [ -e /sys/bus/platform/drivers/efi-framebuffer/efi-framebuffer.0 ] && \
        put efi-framebuffer.0 /sys/bus/platform/drivers/efi-framebuffer/unbind
fi

if lsmod | grep -q '^nvidia'; then
    touch "$STATE/nvidia"
    for m in nvidia_uvm nvidia_drm nvidia_modeset nvidia; do
        lsmod | grep -q "^$m " && run modprobe -r "$m"
    done
fi

[ -n "$PASSTHRU_DRYRUN" ] || sleep 3
exit 0
'''

DISPLAY_END = r'''
if [ -e "$STATE/nvidia" ]; then
    run modprobe nvidia_drm
    run modprobe nvidia_uvm
fi

if [ -f "$STATE/consoles" ]; then
    while read -r vt; do
        put 1 "/sys/class/vtconsole/$vt/bind"
    done < "$STATE/consoles"
fi

DM=$(cat "$STATE/dm" 2>/dev/null)
if [ -n "$DM" ]; then
    [ -n "$PASSTHRU_DRYRUN" ] || sleep 2
    log "возвращаю $DM"
    run systemctl start "$DM.service"
fi
rm -f "$STATE/dm" "$STATE/consoles" "$STATE/nvidia"
exit 0
'''

DISPATCHER_SCRIPT = r'''#!/bin/bash
# libvirt hook dispatcher: runs /etc/libvirt/hooks/qemu.d/<vm>/<op>/<phase>/* in order.
VM_NAME="$1"; VM_ACTION="$2"; VM_PHASE="$3"
HOOK_DIR="/etc/libvirt/hooks/qemu.d/$VM_NAME/$VM_ACTION/$VM_PHASE"
[ -d "$HOOK_DIR" ] || exit 0
for script in "$HOOK_DIR"/*; do
    [ -x "$script" ] || continue
    "$script" "$@" || exit $?
done
'''


def files(cfg, cores=None, dm=None):
    """{relative path under qemu.d/<vm>/: script text}."""
    cores = cores if cores is not None else host.cpu_cores()
    dm = dm if dm is not None else (host.display_manager() or "sddm")
    out = {}
    begin = lambda ph: COMMON.format(name=cfg.name, phase=ph)

    host_cpus = ""
    isolate = 0
    if cfg.pin and cfg.isolate:
        p = model.plan_pinning(cores, cfg.cores, cfg.threads)
        if not p.all_cores:
            host_cpus, isolate = model.cpulist(p.host_cpus), 1
    hp = cfg.ram_gib * 512 if cfg.hugepages else 0
    governor = 1 if cfg.perf_hooks else 0
    if hp or isolate or governor:
        out["prepare/begin/10-passthru-perf.sh"] = begin("prepare/begin") + PERF_BEGIN.format(
            host_cpus=host_cpus, hugepages=hp, governor=governor, isolate=isolate)
        out["release/end/10-passthru-perf.sh"] = begin("release/end") + PERF_END

    if cfg.gpu:
        out["prepare/begin/90-passthru-display.sh"] = begin("prepare/begin") + DISPLAY_BEGIN.format(
            dm=dm, unbind=1 if cfg.unbind_console else 0)
        out["release/end/20-passthru-display.sh"] = begin("release/end") + DISPLAY_END
    return out


def install_script(cfg, names):
    lines = [
        "#!/bin/bash",
        f"# Ставит хуки VM {cfg.name}. Запуск: sudo bash {os.path.join(cfg.bundle_dir, 'install-hooks.sh')}",
        "set -euo pipefail",
        "ROOT=${PASSTHRU_ROOT:-}  # only for testing into a scratch dir",
        '[ -n "$ROOT" ] || [ "$(id -u)" = 0 ] || { echo "Нужен root: sudo bash $0"; exit 1; }',
        'SRC="$(dirname "$(readlink -f "$0")")/hooks"',
        f'DST="$ROOT{HOOK_ROOT}/{cfg.name}"',
        "RESTART=0",
        f'if [ ! -x "$ROOT{DISPATCHER}" ]; then',
        f'    install -Dm755 "$SRC/dispatcher" "$ROOT{DISPATCHER}"',
        "    RESTART=1",
        "fi",
        "# убрать старые файлы passthru этой VM (чужие не трогаем)",
        'if [ -d "$DST" ]; then find "$DST" -name "*-passthru-*.sh" -delete; fi',
    ]
    for n in names:
        lines.append(f'install -Dm755 "$SRC/{n}" "$DST/{n}"')
    lines += [
        'echo "Хуки установлены в $DST:"',
        'find "$DST" -type f | sort',
        'if [ "$RESTART" = 1 ] && [ -z "$ROOT" ]; then',
        '    echo "Диспетчер хуков был новый — перезапускаю libvirt (запущенные VM продолжат работать)"',
        "    systemctl try-restart libvirtd.service virtqemud.service",
        "fi",
    ]
    return "\n".join(lines) + "\n"


def uninstall_script(cfg):
    return "\n".join([
        "#!/bin/bash",
        f"# Удаляет хуки VM {cfg.name}, поставленные passthru.",
        "set -euo pipefail",
        '[ "$(id -u)" = 0 ] || { echo "Нужен root: sudo bash $0"; exit 1; }',
        f"DST={HOOK_ROOT}/{cfg.name}",
        'if [ -d "$DST" ]; then find "$DST" -name "*-passthru-*.sh" -delete; find "$DST" -type d -empty -delete; fi',
        'echo "Готово"',
    ]) + "\n"


def installed_state(cfg, wanted):
    """'ok' | 'missing' | 'outdated' | 'unknown' by comparing files on disk."""
    base = os.path.join(HOOK_ROOT, cfg.name)
    try:
        for rel, text in wanted.items():
            with open(os.path.join(base, rel)) as f:
                if f.read() != text:
                    return "outdated"
    except FileNotFoundError:
        return "missing"
    except PermissionError:
        return "unknown"
    return "ok"
